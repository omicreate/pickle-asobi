/**
 * ピクルくんクイズの問題。
 * どの問題も、照合済みの知識カード（PickleballIQ/根拠/知識カード.md の PBK）か、
 * USA Pickleball 公式ルールブック 2026 の条文を根拠にする（source に書く）。
 * kids：文字が読めなくても答えられるよう、絵（pic）と読み上げで出す。
 * player：大人・選手向け。difficulty 1〜3（おとなは2まで、せんしゅは3まで）。
 */
import type { PicId } from './pics'

export interface QChoice {
  id: string
  text: string
  pic?: PicId
}

export interface Question {
  id: string
  level: 'kids' | 'player'
  difficulty: 1 | 2 | 3
  prompt: string
  choices: QChoice[]
  answerId: string
  explain: string
  source: string
}

/** 選択肢：[文字, 絵] */
type C = [string, PicId?]
const c = (text: string, pic?: PicId): C => [text, pic]

const q = (id: string, level: Question['level'], difficulty: Question['difficulty'], prompt: string, choices: C[], explain: string, source: string): Question => ({
  id,
  level,
  difficulty,
  prompt,
  // 1つめの選択肢を正解として書く（出すときに並べかえる）
  choices: choices.map(([text, pic], i) => ({ id: `${id}-${i}`, text, ...(pic ? { pic } : {}) })),
  answerId: `${id}-0`,
  explain,
  source,
})

